#!/bin/bash
# اليوم 9: أوامر لينكس

pwd              # أنا وين؟
ls               # وش في المجلد؟
mkdir test       # أنشئ مجلداً
cd test          # ادخله
touch a.txt      # أنشئ ملفاً فارغاً
cp a.txt b.txt   # انسخ
mv b.txt c.txt   # أعد التسمية / انقل
rm c.txt         # احذف
rm a.txt         # احذف الباقي عشان يفضى المجلد
cd ..            # ارجع مجلداً
rmdir test       # يحذف المجلد لأنه صار فارغاً
